/// The Magic Lantern app's effect catalogue (`wl.smartled.rgb` 6.11.10,
/// string arrays `modes_group0..7` / `modes_groupN_command`), verbatim ids,
/// grouped as the app's Mode tabs. Names are plain-English rewrites of the
/// vendor's ("7-Color Jump" → "Rainbow switching", "R-G-B" → "Red, green &
/// blue", "Back" → "(reverse)"); the vendor tab is kept in each comment below.
/// The id goes into byte 3 of `7E 05 03 <id> 06 FF FF 00 EF`. Do not renumber.
class MagicLanternMode {
  final int id;
  final String group;
  final String name;
  const MagicLanternMode(this.id, this.group, this.name);

  /// Tab-qualified label so the 213-entry list stays scannable.
  String get label => '$group · $name';
}

